/**
 * Generates the Nigeria state-outline SVG markup seeded into
 * `about-page.energy-map-section.mapSvg` and
 * `projects-page.footprint-map-section.mapSvg`.
 *
 *   node scripts/build-nigeria-map-svg.mjs
 *
 * The geometry comes from the npm package `@svg-maps/nigeria`, which
 * frontend/components/about/EnergyAccessMap.tsx and
 * frontend/components/projects/FootprintMap.tsx both render directly. Only the
 * geometry is captured — every `<path>` keeps its `data-state-id` and carries no
 * fill/stroke, because both maps colour each state at runtime from the
 * `states[]` CMS data. Baking colours in would freeze the choropleth.
 *
 * Writes every output from the same run so they cannot drift:
 *   src/seed/about-map-svg.ts                    — imported by about-page-copy.ts
 *                                                  and projects-page-copy.ts
 *   seed-manifests/about-page/nigeria-map.svg    — read by apply-about-media-to-cms.cjs
 *   seed-manifests/projects-page/nigeria-map.svg — read by apply-projects-media-to-cms.cjs
 */
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const CMS_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const FRONTEND_ROOT = path.join(path.resolve(CMS_ROOT, '..'), 'frontend');

// @svg-maps/nigeria is a frontend dependency — resolve it from there.
const require = createRequire(path.join(FRONTEND_ROOT, 'package.json'));
const map = require('@svg-maps/nigeria');
const data = map.default ?? map;

const paths = data.locations
  .map((location) => `<path data-state-id="${location.id}" d="${location.path}" />`)
  .join('');
const svg = `<svg viewBox="${data.viewBox}" xmlns="http://www.w3.org/2000/svg">${paths}</svg>`;

for (const page of ['about-page', 'projects-page']) {
  const destination = path.join(CMS_ROOT, 'seed-manifests', page);
  await fs.mkdir(destination, { recursive: true });
  await fs.writeFile(path.join(destination, 'nigeria-map.svg'), svg, 'utf8');
}
await fs.writeFile(
  path.join(CMS_ROOT, 'src', 'seed', 'about-map-svg.ts'),
  `// GENERATED by scripts/build-nigeria-map-svg.mjs from @svg-maps/nigeria — do not edit by hand.\n` +
    `// ${data.locations.length} state outlines, viewBox "${data.viewBox}". Colours are applied at\n` +
    `// runtime by EnergyAccessMap.tsx / FootprintMap.tsx, so no fill/stroke is baked in.\n` +
    `export const nigeriaMapSvg =\n  ${JSON.stringify(svg)};\n`,
  'utf8'
);

console.log(`${data.locations.length} state paths, ${svg.length} chars written.`);
