/**
 * Write the Cloudinary URLs, alt text and the Nigeria map SVG markup into the
 * LIVE About entry — media fields only, every copy field left exactly as stored.
 *
 *   node scripts/apply-about-media-to-cms.cjs --dry-run    # report, write nothing
 *   node scripts/apply-about-media-to-cms.cjs              # apply, then publish
 *   node scripts/apply-about-media-to-cms.cjs --restore    # roll back from the backup
 *
 * CommonJS on purpose: @strapi/strapi's ESM build fails to resolve its own
 * `lodash/fp` directory import under Node's ESM loader.
 *
 * bootstrap() only seeds an About entry when there isn't one, so the seed file
 * and the database diverge once the entry exists. This closes that gap without
 * touching the seed-once guard. It goes through Strapi's document service rather
 * than SQL because the About document has separate draft and published entity
 * trees, and repeatable components are ordered through *_cmps link tables.
 *
 * Mirrors scripts/apply-home-media-to-cms.cjs.
 */
const fs = require('node:fs');
const path = require('node:path');
const { createStrapi, compileStrapi } = require('@strapi/strapi');

const CMS_ROOT = path.resolve(__dirname, '..');
const PAGE_NAME = 'about-page';
const MANIFEST_PATH = path.join(CMS_ROOT, 'seed-manifests', PAGE_NAME, 'manifest.json');
const BACKUP_PATH = path.join(CMS_ROOT, 'seed-manifests', PAGE_NAME, 'pre-update-backup.json');
const MAP_SVG_PATH = path.join(CMS_ROOT, 'seed-manifests', PAGE_NAME, 'nigeria-map.svg');

const DRY_RUN = process.argv.includes('--dry-run');
const RESTORE = process.argv.includes('--restore');

/**
 * Fields that carry no uploaded asset and so have no manifest row: the energy
 * map's inline SVG, generated by scripts/build-nigeria-map-svg.mjs from the same
 * @svg-maps/nigeria data EnergyAccessMap.tsx renders.
 */
const MARKUP_PATCHES = [
  {
    component: 'about-page.energy-map-section',
    paths: [[{ field: 'mapSvg' }]],
    value: fs.readFileSync(MAP_SVG_PATH, 'utf8'),
  },
];

/** Media fields that intentionally have no `_alt_text` sibling. */
const NO_ALT_TEXT = new Set(['bentoVideo']);

/** Dynamic zones need populate declared per component. */
const SECTION_POPULATE = {
  'about-page.hero-section': { populate: '*' },
  'about-page.mandate-section': { populate: '*' },
  'about-page.market-section': { populate: '*' },
  'about-page.energy-map-section': { populate: '*' },
  'about-page.framework-section': { populate: '*' },
  'about-page.partners-section': { populate: { groups: { populate: '*' } } },
  'about-page.milestones-section': { populate: '*' },
  'about-page.download-cta-section': { populate: '*' },
};

/** Walks `paths` into `section`, returning the owning object and leaf key. */
function resolve(section, segments) {
  let node = section;
  for (const segment of segments.slice(0, -1)) {
    node = node?.[segment.field];
    if (segment.index !== undefined) node = node?.[segment.index];
    if (node == null) return null;
  }
  const last = segments.at(-1);
  if (last.index !== undefined) {
    node = node?.[last.field];
    return node?.[last.index] ? { owner: node[last.index], key: last.field } : null;
  }
  return node && typeof node === 'object' ? { owner: node, key: last.field } : null;
}

function buildPatches() {
  const manifest = JSON.parse(fs.readFileSync(MANIFEST_PATH, 'utf8'));
  const patches = [];
  for (const row of manifest) {
    if (row.status !== 'ok' || !row.cloudinaryUrl) {
      throw new Error(`manifest row ${row.localFile} is not uploaded (status: ${row.status})`);
    }
    const segments = row.paths[0];
    const leaf = segments.at(-1).field;
    patches.push({ component: row.component, paths: row.paths, field: leaf, value: row.cloudinaryUrl });
    if (!NO_ALT_TEXT.has(leaf)) {
      const altSegments = [...segments.slice(0, -1), { ...segments.at(-1), field: `${leaf}_alt_text` }];
      patches.push({
        component: row.component,
        paths: [altSegments],
        field: `${leaf}_alt_text`,
        value: row.altText,
      });
    }
  }
  return [...patches, ...MARKUP_PATCHES.map((p) => ({ ...p, field: p.paths[0].at(-1).field }))];
}

async function main() {
  const appContext = await compileStrapi({ appDir: CMS_ROOT, distDir: path.join(CMS_ROOT, 'dist') });
  const strapi = await createStrapi(appContext).load();

  try {
    const about = await strapi.documents('api::about.about').findFirst({
      status: 'draft',
      populate: { sections: { on: SECTION_POPULATE } },
    });
    if (!about?.sections?.length) throw new Error('no About draft with sections found');

    const patches = RESTORE
      ? JSON.parse(fs.readFileSync(BACKUP_PATH, 'utf8')).map((row) => ({
          component: row.component,
          paths: row.paths,
          field: row.paths[0].at(-1).field,
          value: row.previousValue,
        }))
      : buildPatches();

    const backup = [];
    const unresolved = [];
    let applied = 0;

    for (const patch of patches) {
      const section = about.sections.find((item) => item.__component === patch.component);
      if (!section) {
        unresolved.push(`${patch.component} (section missing)`);
        continue;
      }
      const target = resolve(section, patch.paths[0]);
      if (!target) {
        unresolved.push(`${patch.component} -> ${JSON.stringify(patch.paths[0])}`);
        continue;
      }
      backup.push({
        component: patch.component,
        paths: patch.paths,
        previousValue: target.owner[target.key] ?? null,
      });
      const before = target.owner[target.key];
      target.owner[target.key] = patch.value;
      applied += 1;
      const changed = before !== patch.value;
      console.log(
        `${changed ? 'patch ' : 'same  '} ${patch.component}.${patch.field} = ` +
          `${String(patch.value).slice(0, 78)}${String(patch.value).length > 78 ? '…' : ''}`
      );
    }

    if (unresolved.length) {
      throw new Error(`${unresolved.length} unresolved path(s):\n  ${unresolved.join('\n  ')}`);
    }
    if (applied === 0) throw new Error('no patches resolved — refusing to write');

    console.log(`\n${applied} field(s) resolved.`);

    if (DRY_RUN) {
      console.log('--dry-run: nothing written.');
      return;
    }

    if (!RESTORE) {
      fs.writeFileSync(BACKUP_PATH, `${JSON.stringify(backup, null, 2)}\n`, 'utf8');
      console.log(`backup written: ${path.relative(CMS_ROOT, BACKUP_PATH)}`);
    }

    await strapi.documents('api::about.about').update({
      documentId: about.documentId,
      data: { sections: about.sections },
    });
    console.log('draft updated.');

    await strapi.documents('api::about.about').publish({ documentId: about.documentId });
    console.log('published — draft and published versions now match.');
  } finally {
    await strapi.destroy();
  }
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
